#!/usr/bin/env bash
# Curate the Pervagans skills catalog from aitmpl (davila7/claude-code-templates).
# - copies each chosen SKILL.md (capped to whole lines under ~8KB) into the
#   backend embed dir as data/<id>.md
# - generates catalog_entries.go (ordered entry list: id, category, features)
# Source of truth: the LIST below. id|srcpath|category|featuresCSV
# srcpath "AUTHORED" => no copy (the .md is hand-written separately).
set -u
