email-composer|enterprise-communication/email-composer|communication|business
professional-communication|enterprise-communication/professional-communication|communication|
'

GO="$OUT/catalog_entries.go"
{
  echo "package skills"
  echo ""
  echo "// Code generated by aitmpl-src/curate.sh from davila7/claude-code-templates."
  echo "// DO NOT EDIT. Re-run the curation script to regenerate."
  echo "// Order here is the catalog display order; each .md lives in data/<id>.md."
  echo ""
  echo "var catalogEntries = []entry{"
} > "$GO"

copied=0; authored=0; missing=0
while IFS='|' read -r id src cat feats; do
  [ -z "${id// /}" ] && continue
  id="${id// /}"; src="${src// /}"; cat="${cat// /}"; feats="${feats// /}"
  # Go features slice literal
  if [ -z "$feats" ]; then
    gof="nil"
  else
    gof="[]string{"
    IFS=',' read -ra fa <<< "$feats"
    for f in "${fa[@]}"; do gof="$gof\"$f\", "; done
    gof="${gof%, }}"
  fi
  printf '\t{id: "%s", category: "%s", features: %s},\n' "$id" "$cat" "$gof" >> "$GO"

  if [ "$src" = "AUTHORED" ]; then
    authored=$((authored+1))
    continue
  fi
  f="$SKILLS_SRC/$src/SKILL.md"
  if [ ! -f "$f" ]; then echo "MISSING: $src" ; missing=$((missing+1)); continue; fi
  # Copy whole lines up to ~8000 bytes (keeps frontmatter + valid UTF-8 boundaries).
  awk 'BEGIN{n=0} {l=length($0)+1; if(n+l>8000) exit; print; n+=l}' "$f" > "$DATA/$id.md"
  copied=$((copied+1))
done <<< "$LIST"

echo "}" >> "$GO"
echo "copied=$copied authored=$authored missing=$missing"
echo "data files: $(ls -1 "$DATA"/*.md 2>/dev/null | wc -l)"
echo "go entries: $(grep -c '{id:' "$GO")"
