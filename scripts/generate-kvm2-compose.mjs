#!/usr/bin/env node
// Generates docker-compose.kvm2.yml: a curated 50-MCP subset that fits a
// 2 vCPU / 8 GB RAM / 100 GB disk Hostinger KVM2 (or equivalent).
// Reads exact ports from scripts/mcps.manifest.json so it never drifts.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const manifest = JSON.parse(readFileSync(join(__dirname, "mcps.manifest.json"), "utf8"));

const API_IDS = [
  "pubmed","icd10","who","cdc","nci","npi","cms","clinicaltrials","chembl",
  "medrxiv","biorxiv","dailymed","medlineplus","nhs","pubchem","endotext",
  "ncbi","fda","wikem","ourworldindata","eyewiki",
];
const HYBRID_IDS = ["cochrane","nejm","bmj","frontiers","rmopen"];
const SCRAPE_IDS = [
  "mayoclinic","clevelandclinic","medscape","webmd","drugscom","rxlist","healthline",
  "nice","cks","bnf","dermnet","orthoinfo","orthobullets","statpearls",
  "emcrit","geekymedics","teachmeanatomy","openanesthesia","gold","gina","librepathology",
];

function findOrDie(id) {
  const s = manifest.servers.find((x) => x.id === id);
  if (!s) throw new Error(`Manifest missing MCP: ${id}`);
  return s;
}

const header = `name: babagemed
# KVM2-friendly stack — frontend + backend + ${API_IDS.length + HYBRID_IDS.length + SCRAPE_IDS.length} hand-picked MCPs.
# Targets a 2 vCPU / 8 GB RAM / 100 GB disk Hostinger KVM2 (or equivalent).
# Estimated usage: ~30 GB disk, ~5-6 GB RAM at idle, ~7 GB under load.
#
# Bring up:
#   docker compose -f docker-compose.yml -f docker-compose.kvm2.yml up -d --build
#
# Auto-generated by scripts/generate-kvm2-compose.mjs — do not hand-edit ports.
x-api-mcp: &api-mcp
  env_file: .env
  environment: { HTTP_ONLY: "1" }
  restart: unless-stopped
  networks: [babagemed]
  deploy:
    resources:
      limits: { memory: 192M, cpus: "0.40" }

x-scrape-mcp: &scrape-mcp
  env_file: .env
  environment: { HTTP_ONLY: "1", SCRAPER_HEADLESS: "true" }
  restart: unless-stopped
  networks: [babagemed]
  deploy:
    resources:
      limits: { memory: 384M, cpus: "0.50" }

services:
`;

const lines = [header];

function emit(group, ids, anchor) {
  lines.push(`  # ─── ${group} (${ids.length}) ─────────────────────────────────────────────────────`);
  for (const id of ids) {
    const s = findOrDie(id);
    lines.push(`  mcp-${s.id}:`);
    lines.push(`    <<: *${anchor}`);
    lines.push(`    build: { context: ., dockerfile: mcps/${s.id}/Dockerfile }`);
    lines.push(`    image: babagemed/mcp-${s.id}:latest`);
    lines.push(`    ports: ["${s.port}:${s.port}"]`);
  }
}

emit("Free-API MCPs", API_IDS, "api-mcp");
emit("Crossref-backed journals", HYBRID_IDS, "api-mcp");
emit("High-yield scrape MCPs (Playwright)", SCRAPE_IDS, "scrape-mcp");

lines.push("\nnetworks:\n  babagemed:\n    name: babagemed\n    driver: bridge\n");

writeFileSync(join(ROOT, "docker-compose.kvm2.yml"), lines.join("\n"));
console.log(`wrote docker-compose.kvm2.yml: ${API_IDS.length + HYBRID_IDS.length + SCRAPE_IDS.length} MCPs`);
